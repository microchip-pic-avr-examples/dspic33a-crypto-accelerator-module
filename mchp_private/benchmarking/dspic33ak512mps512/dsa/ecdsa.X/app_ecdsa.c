#define SIGN
#define BLOCKING

#define SESSION_ID      0x1U

static inline void runHardwareTest(uint8_t *hash, uint32_t hashLength, 
        uint8_t *signature, uint32_t signatureLength, uint8_t *publicKey, uint32_t publicKeyLength,
        uint8_t *privateKey, uint32_t privateKeyLength, crypto_EccCurveType_E eccCurveType)
{
#ifdef BLOCKING
    int8_t hashStatus = 0;   
    #ifdef SIGN
        P28_setHigh();
    #endif
        ////Common Crypto ECDSA SIGN***********************************************************************************************************************
        Crypto_DigiSign_Ecdsa_Sign(CRYPTO_HANDLER_HW_INTERNAL, hash, hashLength, signature, signatureLength, privateKey, privateKeyLength, eccCurveType, SESSION_ID);
    #ifdef SIGN
        P28_setLow();
    #endif   

    #ifndef SIGN
        P28_setHigh();
    #endif
        ////Common Crypto ECDSA VERIFY*********************************************************************************************************************
        Crypto_DigiSign_Ecdsa_Verify(CRYPTO_HANDLER_HW_INTERNAL, hash, hashLength, signature, signatureLength, publicKey, publicKeyLength, &hashStatus, eccCurveType, SESSION_ID);
    #ifndef SIGN
        P28_setLow();
    #endif
#else
    while(Crypto_DigiSign_Ecdsa_Hw_ClearMemory_GetStatus() != CRYPTO_DIGISIGN_OPERATION_COMPLETED)
    {
    }
    #ifdef SIGN
        P28_setHigh();
    #endif
        ////Common Crypto ECDSA SIGN***********************************************************************************************************************
        (void)Crypto_DigiSign_Ecdsa_Sign_Start(CRYPTO_HANDLER_HW_INTERNAL, hash, hashLength, privateKey, privateKeyLength, eccCurveType, SESSION_ID);
        
        while(Crypto_DigiSign_Ecdsa_Sign_GetStatus() != CRYPTO_DIGISIGN_OPERATION_COMPLETED)
        {
        }
        
    #ifdef SIGN
        P28_setLow();
    #endif   
        (void)Crypto_DigiSign_Ecdsa_Sign_GetResult(signature, signatureLength);
        while(Crypto_DigiSign_Ecdsa_Hw_ClearMemory_GetStatus() != CRYPTO_DIGISIGN_OPERATION_COMPLETED)
        {
        }
    #ifndef SIGN
        P28_setHigh();
    #endif
        ////Common Crypto ECDSA VERIFY*********************************************************************************************************************
        (void)Crypto_DigiSign_Ecdsa_Verify_Start(CRYPTO_HANDLER_HW_INTERNAL, hash, hashLength, signature, signatureLength, publicKey, publicKeyLength, eccCurveType, SESSION_ID);
        while(Crypto_DigiSign_Ecdsa_Verify_GetStatus() != CRYPTO_DIGISIGN_OPERATION_COMPLETED)
        {
        }
    #ifndef SIGN
        P28_setLow();
    #endif
        (void)Crypto_DigiSign_Ecdsa_Verify_GetResult();
#endif
    
}


